export function getThikrForHour(hour: number): HourlyThikr {
  const normalizedHour = ((Math.floor(hour) % 24) + 24) % 24;
  const found = HOURLY_ADHKAR.find((t) => t.hour === normalizedHour);
  return found || HOURLY_ADHKAR[0];
}

export function getCurrentHourlyThikr(): HourlyThikr {
  return getThikrForHour(new Date().getHours());
}
